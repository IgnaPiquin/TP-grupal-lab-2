-- Modelo inicial de un gestor de identidades y accesos (IAM).
-- Motor: Oracle Database. Ejecutar conectado al esquema de la aplicación APEX.
-- Cada solicitud pide el alta, baja o modificación de un rol para un empleado.
-- Los roles heredados por el puesto se consultan mediante PUESTO_ROL;
-- EMPLEADO_ROL guarda asignaciones directas o concedidas por una solicitud.

CREATE TABLE area (
    area_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR2(100 CHAR) NOT NULL,
    descripcion   VARCHAR2(500 CHAR),
    activo        CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_area PRIMARY KEY (area_id),
    CONSTRAINT uq_area_nombre UNIQUE (nombre),
    CONSTRAINT ck_area_activo CHECK (activo IN ('S', 'N'))
);

CREATE TABLE puesto (
    puesto_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR2(100 CHAR) NOT NULL,
    descripcion   VARCHAR2(500 CHAR),
    activo        CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_puesto PRIMARY KEY (puesto_id),
    CONSTRAINT uq_puesto_nombre UNIQUE (nombre),
    CONSTRAINT ck_puesto_activo CHECK (activo IN ('S', 'N'))
);

CREATE TABLE rol (
    rol_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo        VARCHAR2(50 CHAR) NOT NULL,
    nombre        VARCHAR2(100 CHAR) NOT NULL,
    descripcion   VARCHAR2(500 CHAR),
    activo        CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (rol_id),
    CONSTRAINT uq_rol_codigo UNIQUE (codigo),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre),
    CONSTRAINT ck_rol_activo CHECK (activo IN ('S', 'N'))
);

CREATE TABLE aplicacion (
    aplicacion_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo        VARCHAR2(50 CHAR) NOT NULL,
    nombre        VARCHAR2(150 CHAR) NOT NULL,
    descripcion   VARCHAR2(500 CHAR),
    url           VARCHAR2(500 CHAR),
    activo        CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_aplicacion PRIMARY KEY (aplicacion_id),
    CONSTRAINT uq_aplicacion_codigo UNIQUE (codigo),
    CONSTRAINT uq_aplicacion_nombre UNIQUE (nombre),
    CONSTRAINT ck_aplicacion_activo CHECK (activo IN ('S', 'N'))
);

CREATE TABLE empleado (
    empleado_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    legajo        VARCHAR2(30 CHAR) NOT NULL,
    nombre        VARCHAR2(100 CHAR) NOT NULL,
    apellido      VARCHAR2(100 CHAR) NOT NULL,
    email         VARCHAR2(254 CHAR) NOT NULL,
    area_id       NUMBER NOT NULL,
    puesto_id     NUMBER NOT NULL,
    fecha_alta    DATE DEFAULT SYSDATE NOT NULL,
    activo        CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_empleado PRIMARY KEY (empleado_id),
    CONSTRAINT uq_empleado_legajo UNIQUE (legajo),
    CONSTRAINT uq_empleado_email UNIQUE (email),
    CONSTRAINT ck_empleado_activo CHECK (activo IN ('S', 'N')),
    CONSTRAINT fk_empleado_area FOREIGN KEY (area_id)
        REFERENCES area (area_id),
    CONSTRAINT fk_empleado_puesto FOREIGN KEY (puesto_id)
        REFERENCES puesto (puesto_id)
);

CREATE TABLE permiso (
    permiso_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    aplicacion_id  NUMBER NOT NULL,
    codigo         VARCHAR2(80 CHAR) NOT NULL,
    nombre         VARCHAR2(150 CHAR) NOT NULL,
    descripcion    VARCHAR2(500 CHAR),
    activo         CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_permiso PRIMARY KEY (permiso_id),
    CONSTRAINT uq_permiso_codigo_app UNIQUE (aplicacion_id, codigo),
    CONSTRAINT ck_permiso_activo CHECK (activo IN ('S', 'N')),
    CONSTRAINT fk_permiso_aplicacion FOREIGN KEY (aplicacion_id)
        REFERENCES aplicacion (aplicacion_id)
);

-- Relación muchos a muchos entre puestos y roles.
CREATE TABLE puesto_rol (
    puesto_id     NUMBER NOT NULL,
    rol_id        NUMBER NOT NULL,
    fecha_desde   DATE DEFAULT SYSDATE NOT NULL,
    fecha_hasta   DATE,
    CONSTRAINT pk_puesto_rol PRIMARY KEY (puesto_id, rol_id),
    CONSTRAINT ck_puesto_rol_fechas CHECK (
        fecha_hasta IS NULL OR fecha_hasta >= fecha_desde
    ),
    CONSTRAINT fk_puesto_rol_puesto FOREIGN KEY (puesto_id)
        REFERENCES puesto (puesto_id),
    CONSTRAINT fk_puesto_rol_rol FOREIGN KEY (rol_id)
        REFERENCES rol (rol_id)
);

-- Relación muchos a muchos entre roles y permisos.
CREATE TABLE rol_permiso (
    rol_id        NUMBER NOT NULL,
    permiso_id    NUMBER NOT NULL,
    CONSTRAINT pk_rol_permiso PRIMARY KEY (rol_id, permiso_id),
    CONSTRAINT fk_rol_permiso_rol FOREIGN KEY (rol_id)
        REFERENCES rol (rol_id),
    CONSTRAINT fk_rol_permiso_permiso FOREIGN KEY (permiso_id)
        REFERENCES permiso (permiso_id)
);

-- Una solicitud apunta a un rol. Para pedir varios roles, se puede agregar
-- una tabla SOLICITUD_DETALLE en una siguiente versión del modelo.
CREATE TABLE solicitud (
    solicitud_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    solicitante_id     NUMBER NOT NULL,
    rol_solicitado_id  NUMBER NOT NULL,
    rol_anterior_id    NUMBER,
    tipo               VARCHAR2(20 CHAR) NOT NULL,
    estado             VARCHAR2(20 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    motivo             VARCHAR2(1000 CHAR) NOT NULL,
    fecha_creacion     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_cierre       TIMESTAMP,
    CONSTRAINT pk_solicitud PRIMARY KEY (solicitud_id),
    CONSTRAINT uq_solicitud_origen UNIQUE (
        solicitud_id, solicitante_id, rol_solicitado_id
    ),
    CONSTRAINT ck_solicitud_tipo CHECK (
        tipo IN ('ALTA', 'BAJA', 'MODIFICACION')
    ),
    CONSTRAINT ck_solicitud_estado CHECK (
        estado IN ('PENDIENTE', 'EN_APROBACION', 'APROBADA', 'RECHAZADA', 'CANCELADA')
    ),
    CONSTRAINT ck_solicitud_roles CHECK (
        (tipo = 'MODIFICACION'
            AND rol_anterior_id IS NOT NULL
            AND rol_anterior_id <> rol_solicitado_id)
        OR
        (tipo IN ('ALTA', 'BAJA') AND rol_anterior_id IS NULL)
    ),
    CONSTRAINT ck_solicitud_cierre CHECK (
        (estado IN ('APROBADA', 'RECHAZADA', 'CANCELADA') AND fecha_cierre IS NOT NULL)
        OR
        (estado IN ('PENDIENTE', 'EN_APROBACION') AND fecha_cierre IS NULL)
    ),
    CONSTRAINT fk_solicitud_empleado FOREIGN KEY (solicitante_id)
        REFERENCES empleado (empleado_id),
    CONSTRAINT fk_solicitud_rol FOREIGN KEY (rol_solicitado_id)
        REFERENCES rol (rol_id),
    CONSTRAINT fk_solicitud_rol_anterior FOREIGN KEY (rol_anterior_id)
        REFERENCES rol (rol_id)
);

-- Asignaciones directas de roles a empleados, incluidas las originadas
-- por solicitudes aprobadas. Los roles del puesto se obtienen por PUESTO_ROL.
CREATE TABLE empleado_rol (
    empleado_rol_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    empleado_id          NUMBER NOT NULL,
    rol_id               NUMBER NOT NULL,
    origen               VARCHAR2(20 CHAR) NOT NULL,
    solicitud_origen_id  NUMBER,
    asignado_por_id      NUMBER,
    motivo               VARCHAR2(500 CHAR),
    fecha_inicio         DATE DEFAULT SYSDATE NOT NULL,
    fecha_fin            DATE,
    CONSTRAINT pk_empleado_rol PRIMARY KEY (empleado_rol_id),
    CONSTRAINT ck_empleado_rol_origen CHECK (
        (origen = 'DIRECTO' AND solicitud_origen_id IS NULL)
        OR
        (origen = 'SOLICITUD' AND solicitud_origen_id IS NOT NULL)
    ),
    CONSTRAINT ck_empleado_rol_fechas CHECK (
        fecha_fin IS NULL OR fecha_fin >= fecha_inicio
    ),
    CONSTRAINT fk_empleado_rol_empleado FOREIGN KEY (empleado_id)
        REFERENCES empleado (empleado_id),
    CONSTRAINT fk_empleado_rol_rol FOREIGN KEY (rol_id)
        REFERENCES rol (rol_id),
    CONSTRAINT fk_empleado_rol_asignador FOREIGN KEY (asignado_por_id)
        REFERENCES empleado (empleado_id),
    CONSTRAINT fk_empleado_rol_solicitud FOREIGN KEY (
        solicitud_origen_id, empleado_id, rol_id
    ) REFERENCES solicitud (
        solicitud_id, solicitante_id, rol_solicitado_id
    )
);

-- Una solicitud puede tener varios pasos de aprobación. El rol define
-- quién está habilitado para aprobar; el empleado registra quién decidió.
-- La aplicación APEX debe validar que el aprobador tenga ese rol y no sea
-- el solicitante; esas reglas dependen de varias tablas y no las cubre una FK.
CREATE TABLE aprobacion (
    aprobacion_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    solicitud_id        NUMBER NOT NULL,
    numero_paso         NUMBER(3) NOT NULL,
    rol_aprobador_id    NUMBER NOT NULL,
    aprobador_id        NUMBER,
    estado              VARCHAR2(20 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    fecha_asignacion    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_decision      TIMESTAMP,
    comentario          VARCHAR2(1000 CHAR),
    CONSTRAINT pk_aprobacion PRIMARY KEY (aprobacion_id),
    CONSTRAINT uq_aprobacion_paso UNIQUE (solicitud_id, numero_paso),
    CONSTRAINT uq_aprobacion_solicitud UNIQUE (aprobacion_id, solicitud_id),
    CONSTRAINT ck_aprobacion_paso CHECK (numero_paso > 0),
    CONSTRAINT ck_aprobacion_estado CHECK (
        (estado = 'PENDIENTE' AND fecha_decision IS NULL)
        OR
        (estado IN ('APROBADA', 'RECHAZADA')
            AND aprobador_id IS NOT NULL
            AND fecha_decision IS NOT NULL)
    ),
    CONSTRAINT fk_aprobacion_solicitud FOREIGN KEY (solicitud_id)
        REFERENCES solicitud (solicitud_id),
    CONSTRAINT fk_aprobacion_rol FOREIGN KEY (rol_aprobador_id)
        REFERENCES rol (rol_id),
    CONSTRAINT fk_aprobacion_empleado FOREIGN KEY (aprobador_id)
        REFERENCES empleado (empleado_id)
);

-- Registro de auditoría. OBJETO_TIPO e ID_REGISTRO permiten registrar
-- eventos sobre distintas entidades; SOLICITUD_ID y APROBACION_ID son vínculos opcionales.
CREATE TABLE log_auditoria (
    log_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    actor_id        NUMBER,
    solicitud_id    NUMBER,
    aprobacion_id   NUMBER,
    objeto_tipo     VARCHAR2(50 CHAR) NOT NULL,
    id_registro     NUMBER,
    accion          VARCHAR2(50 CHAR) NOT NULL,
    fecha_evento    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    detalle         CLOB,
    CONSTRAINT pk_log_auditoria PRIMARY KEY (log_id),
    CONSTRAINT ck_log_aprobacion_solicitud CHECK (
        aprobacion_id IS NULL OR solicitud_id IS NOT NULL
    ),
    CONSTRAINT fk_log_actor FOREIGN KEY (actor_id)
        REFERENCES empleado (empleado_id),
    CONSTRAINT fk_log_solicitud FOREIGN KEY (solicitud_id)
        REFERENCES solicitud (solicitud_id),
    CONSTRAINT fk_log_aprobacion FOREIGN KEY (aprobacion_id, solicitud_id)
        REFERENCES aprobacion (aprobacion_id, solicitud_id)
);

COMMENT ON TABLE empleado_rol IS
    'Asignaciones directas o por solicitud; los roles heredados del puesto se consultan mediante PUESTO_ROL.';
COMMENT ON TABLE solicitud IS
    'Cada fila solicita un rol para un empleado; admite alta, baja o modificación de rol.';
COMMENT ON TABLE aprobacion IS
    'Pasos de aprobación de una solicitud, con el rol requerido y el empleado que tomó la decisión.';
COMMENT ON TABLE log_auditoria IS
    'Eventos de auditoría asociados opcionalmente a un empleado, una solicitud y una aprobación.';
